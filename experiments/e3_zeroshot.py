"""E3 — zero-shot transfer (design doc §6 E3, H1): evaluate a
memory-trained GNN on merge/split (lattice surgery) data, with region/phase
features populated (unmasked — this is real surgery data, not memory
training data). Also demonstrates that MLP/CNN cannot even be evaluated
here: a fixed-input decoder built for a memory-sized input is handed a
surgery-sized one and reports "N/A — architecturally infeasible" instead
of crashing or silently mis-decoding (design doc §5.4's own framing —
"report it as a row of N/A, not a gap in your experiments").
"""

from __future__ import annotations

import torch

from circuits.lattice_surgery import load_generated_circuit
from data.generate import sample_shots
from data.to_graph import GraphBuildContext, batch_to_graphs
from experiments.common import ExperimentResult, evaluate_gnn
from models.cnn_decoder import CNNDecoder
from models.errors import ShapeInfeasibleError
from models.gnn_decoder import GNNDecoder
from models.mlp_decoder import MLPDecoder


def evaluate_gnn_zero_shot(
    model: GNNDecoder,
    surgery_circuit_path: str,
    patch_dimension: float,
    observable_kind: str,
    shots: int = 2000,
    seed: int = 0,
    p: float | None = None,
    k: int | None = None,
) -> ExperimentResult:
    """`p`/`k` are recorded on the result but not used to build the
    circuit here — the circuit at `surgery_circuit_path` was already
    generated by the caller at some (k, p); pass those same values through
    so results/report.py doesn't silently merge rows from different
    physical error rates into one aggregate (a real bug caught by actually
    rerunning scripts/reproduce.sh at a different --p and finding it mixed
    into the same table row as the first run)."""
    circuit = load_generated_circuit(surgery_circuit_path)
    ctx = GraphBuildContext.build(circuit, patch_dimension=patch_dimension)
    batch = sample_shots(circuit, shots=shots, seed=seed)
    graphs = batch_to_graphs(batch, ctx, observable_kind=observable_kind, mask_surgery_features=False)

    rate = evaluate_gnn(model, graphs)

    return ExperimentResult(
        experiment="E3",
        decoder="gnn",
        observable_kind=observable_kind,
        seed=seed,
        p=p,
        k=k,
        logical_error_rate=rate,
        extra={"zero_shot": True, "shots": shots},
    )


def evaluate_fixed_input_infeasibility(
    memory_num_detectors: int,
    memory_grid_shape: tuple[int, int, int],
    surgery_num_detectors: int,
    surgery_grid_shape: tuple[int, int, int],
    observable_kind: str,
) -> tuple[ExperimentResult, ExperimentResult]:
    """Builds MLP/CNN at the memory circuit's own size, then feeds them a
    surgery-shaped input (drawn from the actual `surgery_num_detectors` /
    `surgery_grid_shape` this run's TQEC circuit produced, not a fixed
    stand-in) and expects ShapeInfeasibleError."""
    mlp = MLPDecoder(input_dim=memory_num_detectors)
    try:
        mlp(torch.randn(4, surgery_num_detectors))
        mlp_result = ExperimentResult(
            experiment="E3", decoder="mlp", observable_kind=observable_kind, logical_error_rate=0.5,
            extra={"unexpected": "MLP did not raise ShapeInfeasibleError on mismatched input"},
        )
    except ShapeInfeasibleError:
        mlp_result = ExperimentResult(experiment="E3", decoder="mlp", observable_kind=observable_kind, status="infeasible")

    cnn = CNNDecoder(grid_shape=memory_grid_shape)
    try:
        cnn(torch.randn(4, *surgery_grid_shape))
        cnn_result = ExperimentResult(
            experiment="E3", decoder="cnn", observable_kind=observable_kind, logical_error_rate=0.5,
            extra={"unexpected": "CNN did not raise ShapeInfeasibleError on mismatched input"},
        )
    except ShapeInfeasibleError:
        cnn_result = ExperimentResult(experiment="E3", decoder="cnn", observable_kind=observable_kind, status="infeasible")

    return mlp_result, cnn_result
